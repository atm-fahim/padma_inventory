-- Requisition + Quotation (Oracle) basic SQL
-- Adjust schema prefix as needed (e.g. PAD_INVENTORY.)

-- REQUISITIONS
CREATE TABLE REQUISITIONS (
  ID               NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ORG_ID           NUMBER DEFAULT 1,
  BRANCH_ID        NUMBER NULL,
  REQUISITION_NO   VARCHAR2(100) UNIQUE,
  REQUISITION_DATE DATE NULL,
  EMPLOYEE_ID      VARCHAR2(100) NULL,
  EMPLOYEE_NAME    VARCHAR2(255) NULL,
  NOTES            CLOB NULL,
  STATUS           NUMBER(3) DEFAULT 1,
  CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE REQUISITION_ITEMS (
  ID             NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  REQUISITION_ID NUMBER NOT NULL,
  ITEM_ID        NUMBER NULL,
  ITEM_NAME      VARCHAR2(400) NOT NULL,
  QUANTITY       NUMBER(12,2) DEFAULT 1,
  UOM            VARCHAR2(50) NULL,
  NOTES          CLOB NULL,
  STATUS         NUMBER(3) DEFAULT 1,
  CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_REQ_ITEMS_REQ FOREIGN KEY (REQUISITION_ID) REFERENCES REQUISITIONS(ID) ON DELETE CASCADE
);

-- QUOTATIONS
CREATE TABLE QUOTATIONS (
  ID              NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ORG_ID          NUMBER DEFAULT 1,
  BRANCH_ID       NUMBER NULL,
  SUPPLIER_ID     NUMBER NULL,
  QUOTATION_NO    VARCHAR2(100) UNIQUE,
  QUOTATION_DATE  DATE NULL,
  EMPLOYEE_ID     VARCHAR2(100) NULL,
  EMPLOYEE_NAME   VARCHAR2(255) NULL,
  SUBTOTAL        NUMBER(12,2) DEFAULT 0,
  DISCOUNT_AMOUNT NUMBER(12,2) DEFAULT 0,
  VAT_AMOUNT      NUMBER(12,2) DEFAULT 0,
  TAX_AMOUNT      NUMBER(12,2) DEFAULT 0,
  TOTAL_AMOUNT    NUMBER(12,2) DEFAULT 0,
  NOTE            CLOB NULL,
  STATUS          VARCHAR2(50) DEFAULT 'draft',
  ACTIVE_STATUS   NUMBER(3) DEFAULT 1,
  CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE QUOTATION_ITEMS (
  ID           NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  QUOTATION_ID NUMBER NOT NULL,
  ITEM_ID      NUMBER NULL,
  ITEM_NAME    VARCHAR2(400) NOT NULL,
  DESCRIPTION  CLOB NULL,
  QUANTITY     NUMBER(10,2) DEFAULT 1,
  UOM          VARCHAR2(50) NULL,
  UNIT_PRICE   NUMBER(12,2) DEFAULT 0,
  DISCOUNT     NUMBER(12,2) DEFAULT 0,
  VAT          NUMBER(12,2) DEFAULT 0,
  TAX          NUMBER(12,2) DEFAULT 0,
  LINE_TOTAL   NUMBER(12,2) DEFAULT 0,
  STATUS       NUMBER(3) DEFAULT 1,
  CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_QT_ITEMS_QT FOREIGN KEY (QUOTATION_ID) REFERENCES QUOTATIONS(ID) ON DELETE CASCADE
);

CREATE TABLE QUOTATION_APPROVALS (
  ID                  NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  QUOTATION_ID         NUMBER NOT NULL,
  APPROVAL_LEVEL       VARCHAR2(50) NULL, -- admin/division_head/md/board
  APPROVED_BY          NUMBER NULL,
  APPROVER_NAME        VARCHAR2(255) NULL,
  APPROVER_DESIGNATION VARCHAR2(255) NULL,
  COMMENTS             CLOB NULL,
  STATUS               VARCHAR2(20) DEFAULT 'pending', -- pending/approved/rejected
  APPROVED_AT          TIMESTAMP NULL,
  CREATED_AT           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_QT_APPR_QT FOREIGN KEY (QUOTATION_ID) REFERENCES QUOTATIONS(ID) ON DELETE CASCADE
);

