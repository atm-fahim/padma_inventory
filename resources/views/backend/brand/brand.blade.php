        function edit(id) {
            $.ajax({
                url: "<?= URL::to('/brand-edit'); ?>/" + id,
                type: 'get',
                data: {},
                dataType: 'JSON',
                success: function (response) {
                    $("#exampleModal").modal("show");
                    $(".id").val(response.id);
                    $("#brand_name").val(response.brand_name);
                    // $("#thumb_img").attr('src',''+response.thumb_image);
                    if (response.id) {
                        $('.submit').text("Update");
                        $('#exampleModalLabel').text("Update Brand");
                    }
                }
            });
        }
